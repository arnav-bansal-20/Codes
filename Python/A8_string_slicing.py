fruit = "mango"
length = len(fruit)
print("Mango is a ", length, " letter word")
print(fruit[0:4]) # slicing 
print(fruit[1:4]) # slicing
print(fruit[:4]) # slicing by default 0:4
print(fruit[2:4]) # slicing from index 2 to 4
# negative slicing
print(fruit[-1]) # last character   
print(fruit[-2]) # second last character
print(fruit[-4:-1]) # slicing from index -4 to -1  is same as 1:4 
